CREATE TABLE inventory_stock (
    product_id BIGINT PRIMARY KEY,
    quantity INTEGER NOT NULL DEFAULT 0,
    reorder_level INTEGER,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_inventory_stock_product FOREIGN KEY (product_id)
        REFERENCES products(id) ON DELETE RESTRICT,
    CONSTRAINT ck_inventory_stock_quantity CHECK (quantity >= 0),
    CONSTRAINT ck_inventory_stock_reorder CHECK (reorder_level >= 0)
);

CREATE TABLE stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    movement_type VARCHAR(32) NOT NULL,
    quantity_change INTEGER NOT NULL,
    quantity_after INTEGER NOT NULL,
    reference_type VARCHAR(64) NOT NULL,
    reference_id BIGINT,
    reason TEXT NOT NULL,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_stock_movements_product FOREIGN KEY (product_id)
        REFERENCES products(id) ON DELETE RESTRICT,
    CONSTRAINT fk_stock_movements_creator FOREIGN KEY (created_by)
        REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT ck_stock_movements_kind CHECK (movement_type IN (
        'PURCHASE_RECEIVE', 'SALE_DEDUCT', 'CUSTOMER_RETURN', 'MANUAL_ADJUSTMENT')),
    CONSTRAINT ck_stock_movements_change CHECK (quantity_change <> 0),
    CONSTRAINT ck_stock_movements_after CHECK (quantity_after >= 0),
    CONSTRAINT ck_stock_movements_before CHECK (
        quantity_after::BIGINT - quantity_change::BIGINT BETWEEN 0 AND 2147483647),
    CONSTRAINT ck_stock_movements_sign CHECK (
        (movement_type IN ('PURCHASE_RECEIVE', 'CUSTOMER_RETURN') AND quantity_change > 0)
        OR (movement_type = 'SALE_DEDUCT' AND quantity_change < 0)
        OR (movement_type = 'MANUAL_ADJUSTMENT' AND quantity_change <> 0)),
    CONSTRAINT ck_stock_movements_reference_type CHECK (length(btrim(reference_type)) > 0),
    CONSTRAINT ck_stock_movements_reference_id CHECK (reference_id > 0),
    CONSTRAINT ck_stock_movements_reference_required CHECK (
        movement_type = 'MANUAL_ADJUSTMENT' OR reference_id IS NOT NULL),
    CONSTRAINT ck_stock_movements_reason CHECK (length(btrim(reason)) > 0)
);

CREATE INDEX idx_stock_movements_product_history
    ON stock_movements (product_id, created_at DESC, id DESC);

CREATE INDEX idx_stock_movements_reference
    ON stock_movements (reference_type, reference_id);

CREATE INDEX idx_stock_movements_history
    ON stock_movements (created_at DESC, id DESC);